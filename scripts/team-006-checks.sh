#!/usr/bin/env bash
# Builds the TEAM-006 production check files (apply-check.sql, verify.sql,
# rollback-check.sql) from up.sql, down.sql and the parts in
# supabase/proposals/team-006-sso/checks/. Writes into the directory given,
# by default the proposal directory. scripts/test-db.sh builds them again
# and fails when the committed files differ, so they always run exactly the
# statements of up.sql and down.sql.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
P="$ROOT/supabase/proposals/team-006-sso"
OUT="${1:-$P}"

# The statements between the file's own "BEGIN;" and "COMMIT;" lines.
body() { awk 'f && /^COMMIT;$/ {exit} f {print} /^BEGIN;$/ {f=1}' "$1"; }
part() {
  awk -v label="$2" -v teacher="$P/checks/teacher.part.sql" '
    /^@TEACHER@$/ { while ((getline line < teacher) > 0) print line; close(teacher); next }
    { gsub(/@LABEL@/, label); print }' "$P/checks/$1"
}
block() { # $1 header, $2 statements file or "", $3 statements name, $4 part, $5 label
  printf '%s\n' "$1"
  echo 'DO $team006_check$'
  cat "$P/checks/declare.part.sql"
  if [[ -n "$2" ]]; then
    echo "-- >>> $3 (unchanged, the lines between its BEGIN; and COMMIT;)"
    body "$2"
    echo "-- <<< $3"
  fi
  part "$4" "$5"
  echo 'END'
  echo '$team006_check$;'
}

GENERATED="-- GENERATED by scripts/team-006-checks.sh from up.sql, down.sql and checks/:
-- do not edit by hand. Procedure: docs/migration-history.md, TEAM-006."

block "-- TEAM-006 apply check for production. Changes nothing: runs exactly the
-- statements of up.sql inside one block, checks the result as a teacher of
-- this database would see it, and then raises an error on purpose, so
-- Postgres undoes everything. Expected result: the error
--   TEAM-006 apply dry run OK: tables 3, functions 11, exposed 0, staff rule 2, ...
-- Any other error, or FAILED, means up.sql must not be applied.
-- Takes the same short table locks as up.sql: run it when no activity runs.
$GENERATED" "$P/up.sql" "up.sql" applied.part.sql "apply dry run" > "$OUT/apply-check.sql"

block "-- TEAM-006 verification, right after up.sql was applied. Changes nothing
-- (ends with an error on purpose). Expected result: the error
--   TEAM-006 verify OK: tables 3, functions 11, exposed 0, staff rule 2, ...
$GENERATED" "" "" applied.part.sql "verify" > "$OUT/verify.sql"

block "-- TEAM-006 rollback check for production, after up.sql was applied.
-- Changes nothing: runs exactly the statements of down.sql inside one block,
-- checks the result and raises an error on purpose, so Postgres undoes
-- everything. Expected result: the error
--   TEAM-006 rollback dry run OK: tables 0, functions 0, staff rule 0, ...
-- Any other error, or FAILED, means down.sql would not work as it is.
-- Takes the same short table locks as down.sql: run it when no activity runs.
$GENERATED" "$P/down.sql" "down.sql" rolled-back.part.sql "rollback dry run" > "$OUT/rollback-check.sql"
