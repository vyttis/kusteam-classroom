#!/usr/bin/env bash
# Builds the TEAM-006 production check files (apply-check.sql, verify.sql,
# rollback-check.sql) from up.sql, down.sql and the parts in
# supabase/proposals/team-006-sso/checks/. Writes into the directory given,
# by default the proposal directory. scripts/test-db.sh builds them again
# and fails when the committed files differ, so they always run exactly the
# statements of up.sql and down.sql.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
P="$ROOT/supabase/proposals/team-006-sso"
OUT="${1:-$P}"

# The statements between the file's own "BEGIN;" and "COMMIT;" lines. A
# check runs them inside one DO block that always ends with an error, so
# they must not contain transaction control of their own: a COMMIT inside a
# top-level DO block would make the dry run real.
body() {
  local out
  if ! out="$(awk 'f && /^COMMIT;$/ {done = 1; exit} f {print} /^BEGIN;$/ {f = 1} END {exit !done}' "$1")"; then
    echo "team-006-checks: no BEGIN; ... COMMIT; in $1" >&2
    exit 1
  fi
  # (A bare END; is left out: inside function bodies it closes a block.)
  if grep -Eiq '^[[:space:]]*(begin|commit|rollback|abort|savepoint|release|start[[:space:]]+transaction)([[:space:]]+(work|transaction))?[[:space:]]*;' <<<"$out" \
    || grep -Eiq '^[[:space:]]*end[[:space:]]+(work|transaction)' <<<"$out" \
    || grep -Eiq '^[[:space:]]*(commit|rollback)([[:space:]]|$)' <<<"$out"; then
    echo "team-006-checks: transaction control inside $1; refusing to build a dry run" >&2
    exit 1
  fi
  printf '%s\n' "$out"
}

statements() { # $1 file, $2 name
  echo "-- >>> $2 (unchanged, the lines between its BEGIN; and COMMIT;)"
  body "$1"
  echo "-- <<< $2"
}

# A check part with the shared teacher check and the expected md5 values.
part() {
  local applied back
  applied="$(tr -d '[:space:]' <"$P/checks/applied.md5")"
  back="$(tr -d '[:space:]' <"$P/checks/rolled-back.md5")"
  awk -v teacher="$P/checks/teacher.part.sql" -v applied="$applied" -v back="$back" '
    /^@TEACHER@$/ { while ((getline line < teacher) > 0) print line; close(teacher); next }
    { gsub(/@APPLIED_MD5@/, applied); gsub(/@ROLLED_BACK_MD5@/, back); print }' "$P/checks/$1"
}

GENERATED='-- GENERATED by scripts/team-006-checks.sh from up.sql, down.sql and checks/:
-- do not edit by hand. Procedure: docs/migration-history.md, TEAM-006.'
OPEN='DO $team006_check$'
CLOSE='END
$team006_check$;'

{
  echo '-- TEAM-006 apply check for production. Changes nothing: runs exactly the'
  echo '-- statements of up.sql inside one block and checks the result (including a'
  echo "-- real teacher's activities through RLS), then runs exactly the statements"
  echo '-- of down.sql and checks that state too, so the way back is proven before'
  echo '-- anything is applied. Ends with an error on purpose, so Postgres undoes'
  echo '-- everything. Expected result: the error'
  echo '--   TEAM-006 apply dry run OK: applied [tables 3, ...]; rolled back [tables 0, ...]'
  echo '-- Any other error, or FAILED, means up.sql must not be applied.'
  echo '-- Takes the same short table locks as up.sql: run it when no activity runs.'
  echo "$GENERATED"
  echo "$OPEN"
  cat "$P/checks/declare.part.sql"
  statements "$P/up.sql" up.sql
  part applied.part.sql
  statements "$P/down.sql" down.sql
  part rolled-back.part.sql
  echo "  RAISE EXCEPTION 'TEAM-006 apply dry run %: applied [%]; rolled back [%]',"
  echo "    CASE WHEN chk_ok_applied AND chk_ok_back THEN 'OK' ELSE 'FAILED' END, chk_msg_applied, chk_msg_back;"
  echo "$CLOSE"
} >"$OUT/apply-check.sql"

{
  echo '-- TEAM-006 verification, right after up.sql was applied. Changes nothing'
  echo '-- (ends with an error on purpose). Expected result: the error'
  echo '--   TEAM-006 verify OK: tables 3, functions 11, ...'
  echo "$GENERATED"
  echo "$OPEN"
  cat "$P/checks/declare.part.sql"
  part applied.part.sql
  echo "  RAISE EXCEPTION 'TEAM-006 verify %: %', CASE WHEN chk_ok_applied THEN 'OK' ELSE 'FAILED' END, chk_msg_applied;"
  echo "$CLOSE"
} >"$OUT/verify.sql"

{
  echo '-- TEAM-006 rollback check for production, after up.sql was applied.'
  echo '-- Changes nothing: runs exactly the statements of down.sql inside one block,'
  echo '-- checks the result and ends with an error on purpose, so Postgres undoes'
  echo '-- everything. Expected result: the error'
  echo '--   TEAM-006 rollback dry run OK: tables 0, functions 0, ...'
  echo '-- Any other error, or FAILED, means down.sql would not work as it is.'
  echo '-- Takes the same short table locks as down.sql: run it when no activity runs.'
  echo "$GENERATED"
  echo "$OPEN"
  cat "$P/checks/declare.part.sql"
  statements "$P/down.sql" down.sql
  part rolled-back.part.sql
  echo "  RAISE EXCEPTION 'TEAM-006 rollback dry run %: %', CASE WHEN chk_ok_back THEN 'OK' ELSE 'FAILED' END, chk_msg_back;"
  echo "$CLOSE"
} >"$OUT/rollback-check.sql"
